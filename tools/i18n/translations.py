def main():
    msgs = po_tool.collect()
    for idx, code in ((0, "zh_CN"), (1, "ja")):
        path = os.path.join(po_tool.LANG, code + ".po")
        existing = po_tool.read_po(path)
        tr = {m: existing.get(m) or (T[m][idx] if m in T else "") for m in msgs}
        po_tool.write_catalog(path, msgs, tr, code, po_tool.CATALOGS[code])
    po_tool.write_catalog(os.path.join(po_tool.LANG, "falcon-ocr.pot"), msgs, {}, "", None)
    unused = [k for k in T if k not in msgs]
    if unused:
        print("translations without msgid:", unused)


if __name__ == "__main__":
    main()
